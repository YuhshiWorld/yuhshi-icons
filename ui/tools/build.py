"""Build Yuhshi UI icons: SVG files, TypeScript index, preview sheet."""
import json, os, subprocess, sys
sys.path.insert(0, os.path.dirname(__file__))
from icons import ICONS

OUT = sys.argv[1] if len(sys.argv) > 1 else 'ui'
STROKE = 1.75


def el(e):
    k = e[0]
    if k == 's':
        return f'<path d="{e[1]}"/>'
    if k == 'c':
        return f'<circle cx="{e[1]}" cy="{e[2]}" r="{e[3]}"/>'
    if k == 'dot':
        return f'<circle cx="{e[1]}" cy="{e[2]}" r="{e[3]}" fill="currentColor" stroke="none"/>'
    if k == 'f':
        return f'<path d="{e[1]}" fill="currentColor" stroke="none"/>'
    if k == 't':
        return f'<path d="{e[1]}" fill="currentColor" fill-opacity="0.16" stroke="none"/>'
    if k == 'ts':
        return f'<path d="{e[1]}" stroke-opacity="0.35"/>'
    raise ValueError(k)


def svg(name, els, title):
    body = ''.join(el(e) for e in els)
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" width="24" height="24" '
            f'fill="none" stroke="currentColor" stroke-width="{STROKE}" stroke-linecap="round" '
            f'stroke-linejoin="round" role="img" aria-label="{title}"><title>{title}</title>{body}</svg>\n')


def title(n):
    return n.replace('-', ' ').capitalize()


os.makedirs(f'{OUT}/svg', exist_ok=True)
index = {}
for name, spec in ICONS.items():
    s = svg(name, spec['els'], title(name))
    open(f'{OUT}/svg/{name}.svg', 'w').write(s)
    entry = {'group': spec['group'], 'svg': s.strip(), 'mirrorInRtl': bool(spec.get('rtl'))}
    if 'active' in spec:
        sa = svg(name + '-active', spec['active'] + spec['els'], title(name) + ' (selected)')
        open(f'{OUT}/svg/{name}-active.svg', 'w').write(sa)
        entry['active'] = sa.strip()
    index[name] = entry

names = list(index)
ts = ['// Generated by build.py — do not edit. Yuhshi UI icons v1.',
      '// Each icon is an SVG string using currentColor; render with SvgXml (React Native) or innerHTML (web).',
      '',
      'export type IconName =',
      *[f"  | '{n}'" for n in names], '  ;', '',
      'export interface IconEntry { group: string; svg: string; active?: string; mirrorInRtl: boolean }', '',
      'export const icons: Record<IconName, IconEntry> = ' + json.dumps(index, indent=2) + ';', '',
      'export const iconNames = Object.keys(icons) as IconName[];', '',
      '/** Returns the SVG string; `selected` picks the tinted active version where one exists (tab bar). */',
      'export function iconSvg(name: IconName, selected = False): string {'.replace('False', 'false'),
      '  const e = icons[name];',
      '  return selected && e.active ? e.active : e.svg;',
      '}', '']
os.makedirs(f'{OUT}/src', exist_ok=True)
open(f'{OUT}/src/index.ts', 'w').write('\n'.join(ts))
print(len(names), 'icons,', sum(1 for v in index.values() if 'active' in v), 'active variants')
